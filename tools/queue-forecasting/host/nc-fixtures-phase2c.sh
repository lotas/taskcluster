cat > "$TAILS/nc11_honest" <<'TAIL_PY'


def main():
    rows, days = scorable()
    if not rows:
        return vacuous(f"the extract has no primary-slice row on {days}, so"
                       f" there is nothing to predict. Either the extract's"
                       f" window does not cover the holdout or the slice is"
                       f" empty in it.")
    covered = sorted({r["day"] for r in rows})
    if covered != days:
        # NOT a pass and not a silent one. The honest fixture claiming the wrong
        # days is the one failure that would make every other fixture in this
        # group refuse for the wrong reason.
        return vacuous(f"the extract covers {covered} of the required {days}."
                       f" The honest fixture must claim exactly the contract's"
                       f" holdout, and NC11_HOLDOUT_DAYS={HOLDOUT_DAYS} may not"
                       f" match the contract's holdout_days.")
    emit(rows)
    report(rows, "every primary-slice row on every required day: scorable")
    return 0


if __name__ == "__main__":
    sys.exit(main())

