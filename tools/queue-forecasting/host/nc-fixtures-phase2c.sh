cat > "$TAILS/nc11_cherry_picked" <<'TAIL_PY'

DROP_FRACTION = 0.25


def main():
    rows, days = scorable()
    if not rows:
        return vacuous("no rows to cherry-pick from")
    # PART 3. COMPLETE DAYS, INCOMPLETE WITHIN THEM. Every required day is still
    # claimed -- so the day block is exactly right and the refusal cannot be that
    # -- and inside each day the rows with the largest y_true are dropped. That is
    # the cherry-pick worth closing: the long tail is where a queue model is
    # worst, and a prediction set without it scores beautifully on a subset of a
    # subset while every column in it is honest.
    kept, dropped = [], 0
    for day in days:
        same = sorted((r for r in rows if r["day"] == day),
                      key=lambda r: r["y_true"])
        # At least one row stays, or the day would vanish and the day-block check
        # would refuse first -- a refusal for the right class and the wrong
        # reason, which is the kind of coverage that reads as real and is not.
        keep_n = max(1, int(round(len(same) * (1.0 - DROP_FRACTION))))
        kept.extend(same[:keep_n])
        dropped += len(same) - keep_n
    if dropped == 0:
        return vacuous(f"{DROP_FRACTION:.0%} of {len(rows)} rows across"
                       f" {len(days)} days rounded to zero dropped rows")
    if sorted({r["day"] for r in kept}) != days:
        return vacuous("dropping the tail lost a whole day, so the day-block"
                       " check would refuse before completeness is reached")
    emit(kept)
    report(kept, f"{len(kept)} of {len(rows)} rows: the {DROP_FRACTION:.0%}"
                 f" largest y_true dropped from every day, days intact")
    return 0


if __name__ == "__main__":
    sys.exit(main())

