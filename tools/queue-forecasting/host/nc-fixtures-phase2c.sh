cat > "$TAILS/nc11_easy_days" <<'TAIL_PY'

CLAIM_DAYS = 2


def main():
    rows, days = scorable()
    if not rows:
        return vacuous("no rows to choose days from")
    if len(days) <= CLAIM_DAYS:
        return vacuous(f"the holdout is {len(days)} day(s), so claiming"
                       f" {CLAIM_DAYS} of them is not a subset")
    # THE DAY BLOCK. The two OLDEST required days, complete within each -- so
    # parts 1, 2 and 3 all pass and the only thing wrong is which days were
    # chosen. This is the vector the first version of `check_day_block` left
    # open: it enforced contiguity and merely RECORDED whether the block was the
    # expected tail, on the reasoning that the trainer might drop a partial final
    # day. It cannot -- `load_config` refuses a non-midnight `as_of_date` -- so
    # the hedge guarded nothing and left an easier earlier holdout scoreable.
    claimed = days[:CLAIM_DAYS]
    kept = [r for r in rows if r["day"] in claimed]
    if not kept:
        return vacuous(f"no row falls on {claimed}")
    if sorted({r["day"] for r in kept}) != claimed:
        return vacuous(f"the extract has rows on only"
                       f" {sorted({r['day'] for r in kept})} of {claimed}, so"
                       f" this would refuse as an extract gap rather than as a"
                       f" chosen block")
    emit(kept)
    report(kept, f"claiming {claimed} of the required {days}: an earlier block,"
                 f" complete within each day it claims")
    return 0


if __name__ == "__main__":
    sys.exit(main())

