#!/usr/bin/env bash
# Phase 2c Task 24 / NC11 clause (c): write the row-set fixtures into a
# qf-research checkout.
#
# Tooling, not a test -- the same shape as nc-fixtures-phase2b.sh. It writes
# files and prints the git commands; it never commits and never pushes, because
# the branch is the operator's to publish with the AGENT's credential. The
# dispatcher's token is read-only and must stay so.
#
#   ./nc-fixtures-phase2c.sh ~/qf-research
#
# WHY A FIXTURE AND NOT A MUTATION. NC11 used to edit a finished probe's
# `predictions.parquet` and watch the evaluation refuse. That worked because the
# relay staged the candidate's own `out/` directory, which carries no recorded
# digest -- so the control passed BECAUSE OF the defect it should have found.
# With the relay now bound to the digest `add_artifact` recorded at finish, a
# post-hoc mutation is refused before the row set is ever read, and the ONLY
# thing that can exercise the row-set property is a candidate that legitimately
# emits an unscorable set.
#
# FIVE SCRIPTS, AND THE FIRST ONE IS THE POINT. `nc11_honest` must be ACCEPTED.
# Without it, an evaluator that refused everything would satisfy every other
# clause in the group, and this suite has voided for exactly that reason before.
set -Eeuo pipefail
trap 'echo "FATAL: ${BASH_SOURCE[0]}:${LINENO} failed (exit $?)" >&2; exit 1' ERR

REPO="${1:-}"
if [ -z "$REPO" ] || [ ! -d "$REPO/.git" ]; then
  echo "usage: $0 <path to a qf-research checkout>" >&2
  exit 2
fi
if [ ! -f "$REPO/trainer/pyproject.toml" ]; then
  echo "$REPO does not look like qf-research: no trainer/pyproject.toml" >&2
  exit 2
fi

EXP="$REPO/research/experiments"
mkdir -p "$EXP"

# THE FIXTURE BRANCH MUST CARRY EVERY FIXTURE, because the suite resolves them
# all from ONE sha (`nc12-sha.txt`). This refuses rather than writing into a
# checkout that has only half of them: NC19's first live run voided with
# `can't open file '/app/trainer/research/experiments/baseline_contract.py'`
# because the 2c fixtures had been committed to a fresh branch off main, which
# does not carry 2b's. A generator that lets that happen is a generator that
# produces a branch the suite cannot use.
missing=""
for needed in extract_contract.py baseline_contract.py; do
  [ -f "$EXP/$needed" ] || missing="$missing $needed"
done
if [ -n "$missing" ]; then
  echo "$REPO/research/experiments is missing:$missing" >&2
  echo >&2
  echo "The NC suite resolves EVERY fixture from one commit -- the sha in" >&2
  echo "host/nc12-sha.txt -- so a branch with only these five scripts makes" >&2
  echo "NC13 and NC19 void. Write 2b's first, then re-run this:" >&2
  echo "    ./nc-fixtures-phase2b.sh $REPO" >&2
  echo "    ./nc-fixtures-phase2c.sh $REPO" >&2
  echo "and commit all seven files in one commit." >&2
  exit 2
fi

# The shared core, written once here and into each file: the fixtures are
# standalone because a probe names ONE path and a sibling import inside the
# sandbox is a second thing to be wrong. The duplication lives in this generator,
# where it is maintained once.
CORE="$(cat <<'CORE_PY'
"""NC11 fixture: MODE_NAME. GENERATED by host/nc-fixtures-phase2c.sh.

WHY THESE FIXTURES EXIST AT ALL. NC11's row-set property used to be exercised by
mutating a finished probe's `predictions.parquet` and watching the evaluation
refuse. That control passed BECAUSE OF a defect: the relay staged the candidate's
own `out/` directory, which has no recorded digest, so bytes could change after a
run succeeded and still be judged as that run. The relay now stages
`artifacts/predictions.parquet` and refuses on the digest `add_artifact` recorded
at finish -- which is correct, and means post-hoc mutation can no longer REACH the
row-set check. The only thing that can is a candidate which legitimately emits an
unscorable prediction set. That is what this file is.

WHAT IT IS NOT. It does not train anything. `p50` and `p90_raw` are constants,
because the property under test is the ROW SET and a fixture with a plausible
model in it invites somebody to read its verdict as a result.

EACH FIXTURE VIOLATES EXACTLY ONE PART, and would satisfy the others:

  nc11_honest        nothing -- the CANARY. Every refusal below is measured
                     against this being accepted; without it, an evaluator that
                     refused everything would satisfy the whole group.
  nc11_relabelled    part 1: row_id disagrees with its own task_id/run_id.
  nc11_ghost_row     part 2: a predicted row the extract does not contain.
  nc11_cherry_picked part 3: complete days, incomplete WITHIN them -- the rows
                     with the largest y_true dropped, which is the cherry-pick
                     that scores beautifully on a subset of a subset.
  nc11_easy_days     the day block: an earlier, easier subset of the holdout,
                     complete within each day it claims.

`nc11_cherry_picked` and `nc11_easy_days` both come back as `row_set_rejected`,
because that is the only thing the job record carries. Their distinctness is not
visible there and is not meant to be: it is in the fixtures, each of which passes
every check but one.

IT FAILS IF ITS OWN VIOLATION IS VACUOUS. A fixture that dropped zero rows, or
relabelled nothing, would emit an honest set, the evaluation would succeed, and
the suite would report a dispatcher failure for a fixture that did nothing. This
programme has shipped exactly that perturbation twice (a `sum_abs_error` of 0.0
multiplied by 1000), so the check is here rather than in the reader's head.
"""
import json
import os
import sys

# The mount points, and the ONE reason they are overridable: the repo proves what
# each fixture emits by running it against the synthetic extract in
# `evaluator/tests/test_evaluate.py` and feeding the result to the real
# evaluator. A fixture nothing can execute is a fixture whose refusal class is a
# guess. The sandbox sets neither variable.
EXTRACT = os.environ.get("NC11_EXTRACT", "/extract")
OUT = os.environ.get("NC11_OUT", "/out")

# The trainer's own holdout length (`config.compute_windows`), which is what the
# contracts are written against. Overridable for the same reason as the paths --
# the synthetic extract is three days long, not five. A MISMATCH WITH THE
# CONTRACT SHOWS UP ON THE HONEST FIXTURE as a day-block refusal, which is
# precisely why the honest one is the canary.
HOLDOUT_DAYS = int(os.environ.get("NC11_HOLDOUT_DAYS", "5"))

# The contract's primary slice. Same story: the candidate does not get to see the
# contract (that is NC9), so this is the convention, and disagreeing with it
# shows up as the honest fixture losing rows.
PRIMARY_SLICE = ("completed",)

MODE = "MODE_NAME"

TARGET_COLUMNS = {"wait_time": "wait_duration_s",
                  "run_duration": "run_duration_s"}

P50 = 600.0
P90 = 3600.0


def required_days(as_of_date, holdout_days):
    """`[as_of_date - holdout_days, as_of_date)`, one calendar day at a time.

    A SECOND IMPLEMENTATION on purpose, like `baseline_contract.py`'s
    `canonical()`: this is agent-authored code inside the sandbox and cannot
    import the trusted module. If the two ever disagree, the disagreement is the
    finding -- and it surfaces on the honest fixture, not silently.
    """
    import datetime
    day = datetime.datetime.strptime(as_of_date, "%Y-%m-%dT%H:%M:%SZ").date()
    return [(day - datetime.timedelta(days=n)).isoformat()
            for n in range(holdout_days, 0, -1)]


def scorable():
    """The honest set: every primary-slice row on every required holdout day.

    Returns `(rows, days)` where `rows` is a list of
    `{task_id, run_id, day, y_true}` sorted by (day, task_id, run_id).
    """
    import pyarrow
    import pyarrow.compute as pc
    import pyarrow.parquet as pq

    with open(os.path.join(EXTRACT, "MANIFEST.json")) as fh:
        manifest = json.load(fh)
    request = manifest["request"]
    y_col = TARGET_COLUMNS[request["target"]]
    days = required_days(request["as_of_date"], HOLDOUT_DAYS)

    table = pq.read_table(
        os.path.join(EXTRACT, "runs.parquet"),
        columns=["task_id", "run_id", "pending_at", "reason_resolved", y_col])
    # The UTC calendar day of `pending_at`: the contract's anchor, and the same
    # derivation the evaluator uses (`pyarrow.compute.strftime`, locale C).
    day = pc.strftime(table.column("pending_at"), format="%Y-%m-%d", locale="C")
    y = table.column(y_col)
    keep = pc.and_(
        pc.is_in(day, value_set=pyarrow.array(days, pyarrow.string())),
        pc.is_in(table.column("reason_resolved"),
                 value_set=pyarrow.array(list(PRIMARY_SLICE),
                                         pyarrow.string())))
    # `is_valid` AND `is_finite`: the evaluator's judged population is
    # `isin(reason, slice) & isfinite(y_true)`, and a null is neither finite nor
    # a false -- `pc.and_` would propagate it and `filter` would drop it, which
    # happens to be right, but only by accident. `fill_null` makes it a
    # decision.
    keep = pc.and_(keep, pc.and_(pc.is_valid(y), pc.is_finite(y)))
    keep = pc.fill_null(keep, False)
    picked = table.append_column("day", day).filter(keep)

    rows = []
    for task_id, run_id, d, value in zip(
            picked.column("task_id").to_pylist(),
            picked.column("run_id").to_pylist(),
            picked.column("day").to_pylist(),
            picked.column(y_col).to_pylist()):
        rows.append({"task_id": str(task_id), "run_id": int(run_id),
                     "day": str(d), "y_true": float(value)})
    rows.sort(key=lambda r: (r["day"], r["task_id"], r["run_id"]))
    return rows, days


def emit(rows, *, row_ids=None):
    """Write `predictions.parquet` with 2b-2's frozen five columns.

    `row_ids` is a LIST rather than a callback, so the labels cannot depend on
    the order this function happens to iterate in -- one fixture supplies
    deliberately wrong ones and an order-sensitive callback would put them on
    rows it did not choose.
    """
    import pyarrow
    import pyarrow.parquet as pq

    if row_ids is None:
        row_ids = [f"{r['task_id']}:{r['run_id']}" for r in rows]
    if len(row_ids) != len(rows):
        raise AssertionError(f"{len(row_ids)} row_ids for {len(rows)} rows")
    table = pyarrow.table({
        "task_id": pyarrow.array([r["task_id"] for r in rows],
                                 pyarrow.string()),
        "run_id": pyarrow.array([r["run_id"] for r in rows], pyarrow.int32()),
        "row_id": pyarrow.array(row_ids, pyarrow.string()),
        "p50": pyarrow.array([P50] * len(rows), pyarrow.float64()),
        "p90_raw": pyarrow.array([P90] * len(rows), pyarrow.float64()),
    })
    pq.write_table(table, os.path.join(OUT, "predictions.parquet"))


def report(rows, note):
    days = sorted({r["day"] for r in rows})
    print(f"    {note}", flush=True)
    print(f"== NC11-FIXTURE: mode={MODE} rows={len(rows)}"
          f" days={len(days)} first={days[0] if days else '-'}"
          f" last={days[-1] if days else '-'} ==", flush=True)


def vacuous(why):
    """The fixture did not do the thing it exists to do. FAIL, loudly.

    Exit 1, so the PROBE fails and the NC clause voids on a fixture it can see
    the problem with -- rather than the probe succeeding with an honest set and
    the clause reporting that the evaluator failed to refuse.
    """
    print(f"FAIL  {MODE} is vacuous: {why}", flush=True)
    print(f"== NC11-FIXTURE: mode={MODE} rows=0 days=0 vacuous=1 ==", flush=True)
    return 1
CORE_PY
)"

write_fixture() {  # write_fixture <name> <tail file>
  local name="$1" tail="$2"
  {
    printf '%s\n' "${CORE//MODE_NAME/$name}"
    cat "$tail"
  } > "$EXP/$name.py"
  echo "wrote research/experiments/$name.py"
}

