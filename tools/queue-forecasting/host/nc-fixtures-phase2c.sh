cat > "$TAILS/nc11_relabelled" <<'TAIL_PY'


RELABEL_EVERY = 10


def main():
    rows, _days = scorable()
    if not rows:
        return vacuous("no rows to relabel")
    # PART 1. A FRACTION of the row_ids is shifted off its own key -- not all of
    # them, and the difference is the whole point of this fixture.
    #
    # Relabelling EVERY row was the first version, and the repo's execution of
    # these fixtures against a real extract showed what it actually produces:
    # `evaluate_refused`, "none of the predicted rows is in the frozen extract".
    # That refusal is correct and is a DIFFERENT property -- predictions made
    # against other data -- and it fires before the row set is examined at all.
    # So a fixture that broke every label would have reported the right-looking
    # failure for the wrong reason, and the NC clause asserting
    # `row_set_rejected` would have failed on a working evaluator.
    #
    # With most keys intact the join finds its rows, and what is left is exactly
    # the question part 1 asks: a row_id that disagrees with the task_id and
    # run_id beside it is either a different join key or a label nobody checked.
    labels, broken = [], 0
    for position, row in enumerate(rows):
        if position % RELABEL_EVERY == 0:
            broken += 1
            labels.append(f"{row['task_id']}:{row['run_id'] + 1}")
        else:
            labels.append(f"{row['task_id']}:{row['run_id']}")
    if broken == 0:
        return vacuous(f"one in {RELABEL_EVERY} of {len(rows)} rows rounded to"
                       f" no relabelled row")
    emit(rows, row_ids=labels)
    report(rows, f"{broken} of {len(rows)} row_ids shifted to run_id+1, the"
                 f" rest honest: the derivation is broken where the join still"
                 f" lands")
    return 0


if __name__ == "__main__":
    sys.exit(main())

TAIL_PY
write_fixture nc11_relabelled "$TAILS/nc11_relabelled"

cat > "$TAILS/nc11_ghost_row" <<'TAIL_PY'


def main():
    rows, _days = scorable()
    if not rows:
        return vacuous("no rows to add a ghost to")
    # PART 2. One extra row whose task_id is not in the extract, with a
    # PERFECTLY WELL-FORMED row_id -- so part 1 passes and the refusal can only
    # be this. A prediction for a row the extract does not contain has no y_true
    # to be scored against, and quietly dropping it would let a candidate pad its
    # coverage.
    ghost = {"task_id": "nc11-ghost-000000000000", "run_id": 0,
             "day": rows[-1]["day"], "y_true": 0.0}
    if any(r["task_id"] == ghost["task_id"] for r in rows):
        return vacuous("the ghost task_id exists in the extract")
    emit(rows + [ghost])
    report(rows + [ghost],
           f"{len(rows)} real rows plus {ghost['task_id']}, which is not in the"
           f" extract")
    return 0


if __name__ == "__main__":
    sys.exit(main())

